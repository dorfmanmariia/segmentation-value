import numpy as np
from scipy.special import logsumexp

from models import add_const


def center(R, X):
    # removes each respondent's average rating (scale use) and the profile means
    X = np.asarray(X, dtype=float)
    return R - R.mean(1, keepdims=True), X - X.mean(0)


def _prepare(R, X, centered):
    if centered:
        Y, Z = center(R, X)
        return Y, Z, R.shape[1] - 1
    return R, add_const(X), R.shape[1]


def _e_step(Y, Z, B, s2, pi, dof):
    ss = ((Y[:, None, :] - (B @ Z.T)[None, :, :]) ** 2).sum(2)
    logp = np.log(pi) - 0.5 * ss / s2 - 0.5 * dof * np.log(2 * np.pi * s2)
    ll = logsumexp(logp, axis=1)
    return np.exp(logp - ll[:, None]), ll.sum()


def latent_class(R, X, K, centered=True, n_starts=20, n_iter=1000, tol=1e-7, seed=0):
    """Latent class regression: respondent i belongs to segment k with prob pi_k,
    and all 20 ratings of i are generated by r_i = Z b_k + e, e ~ N(0, s2_k)."""
    Y, Z, dof = _prepare(R, X, centered)
    n, p = Y.shape[0], Z.shape[1]
    rng = np.random.default_rng(seed)
    best = None
    for _ in range(n_starts):
        post = rng.dirichlet(np.ones(K), n)
        ll_old = -np.inf
        for _ in range(n_iter):
            w = post.sum(0)
            if w.min() < 1e-6:
                break
            pi = w / n
            B = np.linalg.lstsq(Z, ((post.T @ Y) / w[:, None]).T, rcond=None)[0].T
            ss = ((Y[:, None, :] - (B @ Z.T)[None, :, :]) ** 2).sum(2)
            s2 = (post * ss).sum(0) / (w * dof)
            post, ll = _e_step(Y, Z, B, s2, pi, dof)
            if ll - ll_old < tol:
                break
            ll_old = ll
        else:
            pass
        if w.min() < 1e-6:
            continue
        if best is None or ll > best["ll"]:
            best = {"B": B, "s2": s2, "pi": pi, "post": post, "ll": ll}

    n_par = K * (p + 1) + K - 1
    best["bic"] = -2 * best["ll"] + np.log(n) * n_par
    entropy = -(best["post"] * np.log(best["post"] + 1e-300)).sum()
    best["icl"] = best["bic"] + 2 * entropy
    best["centered"] = centered
    best["labels"] = best["post"].argmax(1)
    return best


def lc_assign(R, X, fit):
    Y, Z, dof = _prepare(R, X, fit["centered"])
    post, _ = _e_step(Y, Z, fit["B"], fit["s2"], fit["pi"], dof)
    return post


def lc_predict(R_train, X_train, X_test, fit):
    post = lc_assign(R_train, X_train, fit)
    X_train = np.asarray(X_train, dtype=float)
    X_test = np.asarray(X_test, dtype=float)
    if fit["centered"]:
        seg_pred = (X_test - X_train.mean(0)) @ fit["B"].T
        return R_train.mean(1, keepdims=True) + post @ seg_pred.T
    return post @ (add_const(X_test) @ fit["B"].T).T
